// 匿名花名：场景词 + 物品词，如「三楼的橘子」「熄灯前的月亮」
const SCENES = [
  '三楼的', '熄灯前的', '天台的', '操场的', '晚自习的', '走廊尽头的',
  '湖边的', '图书馆的', '食堂角落的', '银杏道上的', '雨后的', '黄昏的',
  '午夜的', '清晨六点的', '期末周的', '毕业季的', '开学那天的', '雪后的',
  '风里的', '窗边的', '台阶上的', '路灯下的', '桥上的', '树荫里的',
];

const ITEMS = [
  '橘子', '月亮', '信封', '汽水', '猫', '火柴', '伞', '星星', '汤勺',
  '纸飞机', '许愿币', '旧球鞋', '草稿纸', '风铃', '钥匙扣', '暖宝宝',
  '荧光笔', '自行车铃', '茶叶蛋', '耳机', '书签', '纽扣', '玻璃瓶',
  '漂流瓶', '小夜灯', '回声', '流星', '萤火',
];

export const randomFlowerName = (rand: () => number = Math.random): string => {
  const s = SCENES[Math.floor(rand() * SCENES.length)];
  const i = ITEMS[Math.floor(rand() * ITEMS.length)];
  return `${s}${i}`;
};
